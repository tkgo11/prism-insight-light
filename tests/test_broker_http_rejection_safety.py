"""Mock-only broker HTTP rejection ambiguity and durable retry safety.

An HTTP timeout/conflict/rate-limit response may be generated by an intermediary
after the order reached KIS. A business-code-looking string in such a response
is not authoritative evidence that no order exists at the broker.
"""

import pytest

from trading.execution_ledger import ExecutionLedger
from trading.execution_outcome import classify_broker_result, rejection_is_ambiguous


class MockKISResponse:
    def __init__(self, status: int, code: str = "APBK0918"):
        self.status = status
        self.code = code

    def getResCode(self):
        return self.status

    def getErrorCode(self):
        return self.code


@pytest.mark.parametrize("http_status", [408, 409, 425, 429, 499])
def test_ambiguous_http_response_cannot_release_order_replay_fence(tmp_path, http_status):
    """Mock transport response; neither a KIS demo fill nor a live order."""
    response = MockKISResponse(http_status)
    ambiguous = rejection_is_ambiguous(response)
    assert ambiguous is True, (
        f"HTTP {http_status} does not prove KIS rejected the order before submission"
    )
    result = {
        "success": False,
        "outcome_unknown": ambiguous,
        "message": f"APBK0918 from HTTP {http_status} intermediary",
    }
    outcome = classify_broker_result(result)
    assert outcome == "unknown"
    ledger_path = tmp_path / f"attempt-{http_status}.json"
    ledger = ExecutionLedger(ledger_path)
    assert ledger.claim("same-account-signal") == (True, None)
    ledger.finalize("same-account-signal", outcome)
    assert ExecutionLedger(ledger_path).claim("same-account-signal") == (
        False, "unknown"
    )


@pytest.mark.parametrize("http_status", [200, 400, 422])
def test_valid_business_rejection_control_remains_retryable(http_status):
    """Conservative transport guard must not disable known business rejection."""
    response = MockKISResponse(http_status, "APBK0918")
    assert rejection_is_ambiguous(response) is False
    assert classify_broker_result({
        "success": False,
        "outcome_unknown": False,
        "message": "APBK0918 - verified business rejection",
    }) == "failed"


@pytest.mark.parametrize("malformed_status", [200.9, 400.9, "４００", "400.0"])
def test_noncanonical_http_status_cannot_prove_business_rejection(malformed_status):
    """Only exact ASCII 3-digit HTTP statuses are authoritative syntax."""
    assert rejection_is_ambiguous(MockKISResponse(malformed_status)) is True


@pytest.mark.parametrize("http_status", [201, 202, 204, 205, 206, 207, 226])
def test_nonstandard_2xx_cannot_release_durable_replay_fence(tmp_path, http_status):
    """A mock 2xx intermediary response is not proof of KIS rejection."""
    ambiguous = rejection_is_ambiguous(MockKISResponse(http_status))
    assert ambiguous is True
    outcome = classify_broker_result({
        "success": False,
        "outcome_unknown": ambiguous,
        "message": "unverified KIS-looking business code",
    })
    assert outcome == "unknown"
    path = tmp_path / f"2xx-{http_status}.json"
    ledger = ExecutionLedger(path)
    assert ledger.claim("account-specific-signal") == (True, None)
    ledger.finalize("account-specific-signal", outcome)
    assert ExecutionLedger(path).claim("account-specific-signal") == (False, "unknown")
